create extension if not exists pgcrypto;

-- ─── RICETTE ─────────────────────────────────────────────────────────
-- "data" contiene la scheda completa (nome, sezione, categoria, piatto,
-- ingredienti, procedimento…) esattamente come nell'app originale.
create table if not exists public.ricette (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  data        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists ricette_user_idx on public.ricette(user_id);

-- ─── IMPOSTAZIONI DELL'ACCOUNT ───────────────────────────────────────
-- brand_name / logo / slug: logo e nome mostrati in home e nella pagina
-- d'accesso; data: sezioni, documenti di stampa, piatti, tema, ecc.
create table if not exists public.user_settings (
  user_id     uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  slug        text unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,40}$'),
  brand_name  text,
  brand_sub   text,
  logo        text,          -- immagine (data URL, ridimensionata dall'app)
  data        jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

