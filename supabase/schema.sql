grant select, insert on public.messaggi_letti to authenticated;

-- persone della brigata (titolare compreso), per destinatari e responsabili
create or replace function public.brigata_people(p_owner uuid)
returns table(user_id uuid, name text, email text, role text)
language sql stable security definer set search_path = public as $$
  select u.id, coalesce(u.raw_user_meta_data->>'full_name', u.raw_user_meta_data->>'name', split_part(u.email, '@', 1)), u.email, 'owner'
    from auth.users u where u.id = p_owner and public.wl_can_read(p_owner)
  union all
  select b.member_id, coalesce(b.name, split_part(b.email, '@', 1)), b.email, b.role
    from public.brigata b where b.owner_id = p_owner and b.status = 'active' and b.member_id is not null and public.wl_can_read(p_owner);
$$;
revoke all on function public.brigata_people(uuid) from public;
grant execute on function public.brigata_people(uuid) to authenticated;

-- ─── STORICO DELLE RICETTE E NOTE DI BRIGATA ─────────────────────────
-- ogni creazione, modifica o eliminazione di una ricetta viene registrata dal database
create table if not exists public.ricette_storia (
  id          bigint generated by default as identity primary key,
  owner_id    uuid not null references auth.users(id) on delete cascade,
  recipe_id   bigint not null,
  user_id     uuid,
  user_name   text,
  action      text not null check (action in ('create','update','delete')),
  old_data    jsonb,
  new_data    jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists ricette_storia_idx on public.ricette_storia(owner_id, recipe_id, created_at desc);
create or replace function public.ricette_log()
returns trigger language plpgsql security definer set search_path = public as $$
declare who uuid := auth.uid(); nm text; o jsonb; n jsonb; own uuid; rid bigint;
begin
  if tg_op = 'DELETE' then o := old.data; own := old.user_id; rid := old.id;
  elsif tg_op = 'INSERT' then n := new.data; own := new.user_id; rid := new.id;
  else o := old.data; n := new.data; own := new.user_id; rid := new.id;
    if o is not distinct from n then return new; end if;
  end if;
  if coalesce(n, o) ? '_cfg' then return coalesce(new, old); end if;
  select coalesce(u.raw_user_meta_data->>'full_name', u.raw_user_meta_data->>'name', split_part(u.email, '@', 1)) into nm from auth.users u where u.id = who;
  insert into public.ricette_storia(owner_id, recipe_id, user_id, user_name, action, old_data, new_data)
  values (own, rid, who, nm, case tg_op when 'INSERT' then 'create' when 'UPDATE' then 'update' else 'delete' end, o, n);
  return coalesce(new, old);
end $$;
drop trigger if exists ricette_log_t on public.ricette;
create trigger ricette_log_t after insert or update or delete on public.ricette for each row execute function public.ricette_log();

